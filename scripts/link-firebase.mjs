#!/usr/bin/env node
// Usage: pnpm link:firebase /path/to/service-account.json [--api-key=... --app-id=... --bucket=...]
// Writes .env.local (gitignored) from a Firebase Admin service-account file. Never commit the output.
import { readFileSync, writeFileSync, existsSync, chmodSync } from "node:fs";

const [file, ...flags] = process.argv.slice(2);
if (!file || !existsSync(file)) {
  console.error("Usage: pnpm link:firebase <service-account.json> [--api-key=...] [--app-id=...] [--bucket=...]");
  process.exit(1);
}
const opt = Object.fromEntries(flags.filter((f) => f.startsWith("--")).map((f) => f.slice(2).split(/=(.*)/s).slice(0, 2)));
const sa = JSON.parse(readFileSync(file, "utf8"));
for (const key of ["project_id", "client_email", "private_key"]) {
  if (!sa[key]) { console.error(`Service account is missing "${key}".`); process.exit(1); }
}

// Keep any values already set in an existing .env.local
const existing = {};
if (existsSync(".env.local")) {
  for (const line of readFileSync(".env.local", "utf8").split("\n")) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) existing[m[1]] = m[2];
  }
}
const pick = (name, fallback) => existing[name] || fallback || "";
const pid = sa.project_id;
const out = [
  "# Generated by scripts/link-firebase.mjs. Gitignored. NEVER commit or share.",
  `NEXT_PUBLIC_FIREBASE_API_KEY=${opt["api-key"] ?? pick("NEXT_PUBLIC_FIREBASE_API_KEY")}`,
  `NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${pick("NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN", `${pid}.firebaseapp.com`)}`,
  `NEXT_PUBLIC_FIREBASE_PROJECT_ID=${pid}`,
  `NEXT_PUBLIC_FIREBASE_APP_ID=${opt["app-id"] ?? pick("NEXT_PUBLIC_FIREBASE_APP_ID")}`,
  `NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${opt.bucket ?? pick("NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET", `${pid}.firebasestorage.app`)}`,
  `FIREBASE_ADMIN_SERVICE_ACCOUNT_JSON=${JSON.stringify(sa)}`,
  `FIREBASE_DATABASE_URL=${opt["database-url"] ?? pick("FIREBASE_DATABASE_URL", `https://${pid}-default-rtdb.firebaseio.com`)}`,
  `DEMO_ADMIN_UID=${pick("DEMO_ADMIN_UID")}`,
  `COOKIE_SAMESITE=${pick("COOKIE_SAMESITE", "lax")}`,
  "",
].join("\n");
writeFileSync(".env.local", out);
try { chmodSync(".env.local", 0o600); } catch {}
const missing = ["NEXT_PUBLIC_FIREBASE_API_KEY", "NEXT_PUBLIC_FIREBASE_APP_ID"].filter((k) => !out.includes(`${k}=\n`) === false);
console.log(`Linked project "${pid}" -> .env.local`);
if (missing.length) console.log(`Still needed (Firebase Console > Project settings > Your apps > Web app): ${missing.join(", ")}`);
